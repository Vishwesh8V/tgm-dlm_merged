#!/usr/bin/env python3
"""
trajectory_analysis.py

Offline analysis of the Stage-1 validation trajectory produced by
`reduced_step_profile.py`. Stage 2/3/4 of the adaptive-step-inference
pipeline.

Ported from a sibling DiffuSeq-derived `trajectory_analysis.py` (a molecule
-> caption task) and adapted for TGM-DLM's caption -> SMILES direction. The
math (Steps 2-4 below) is unchanged; the only real adaptation is *which*
token positions get an adaptive schedule at all.

The reference hardcoded a hardcoded caption-only range (`ACTIVE_POSITIONS =
range(87, 128)`) because everything before that was preserved source input,
never generated by the model. TGM-DLM generates every position of the SMILES
sequence (the caption is external cross-attention conditioning), so there is
no equivalent fixed boundary -- `infer_active_positions()` below instead
derives "active" positions directly from the Stage-1 profile: a position is
active if enough validation examples actually extend that far (i.e. it
usually holds a real SMILES token rather than padding). Positions that are
almost always padding fall back to the uniform baseline schedule, same as
`ACTIVE_POSITIONS` exclusion did in the reference.

Stage 2:
    E_i(lambda) -> smooth E_i(lambda) -> dE_i/dlambda

Stage 3:
    dE_i/dlambda -> a_i(lambda) -> p_i(lambda)
    and plot density bars for selected token positions.

Stage 4:
    p_i(lambda) -> practical finite-step allocation J[K, L]

No model/checkpoint/GPU is needed for any of this -- it all runs on the
Stage-1 .npz.
"""

import argparse
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from scipy.interpolate import UnivariateSpline


def infer_active_positions(valid_count, min_frac=0.5):
    """
    A position is "active" (worth an adaptive schedule) if it has real
    (non-pad) validation coverage across most sampled timesteps -- i.e. most
    profiled SMILES extend to that position. Positions that are almost
    always padding don't have a meaningful loss curve to fit and are left on
    the uniform baseline.

    This replaces the reference's hardcoded `ACTIVE_POSITIONS = range(87,
    128)` (a fixed caption region), since TGM-DLM has no equivalent fixed
    boundary -- every position is generated, and "active" here is purely a
    data-coverage question.
    """
    T, L = valid_count.shape
    coverage = (valid_count > 0).sum(axis=0) / float(T)
    active = tuple(int(i) for i in np.flatnonzero(coverage >= min_frac))
    if not active:
        raise RuntimeError(
            f"No position reached min_frac={min_frac} validation coverage; "
            "lower --min-active-frac or check the Stage-1 profile."
        )
    return active


def _default_plot_positions(active_positions, n=5):
    """Evenly spaced representative positions for diagnostic plots."""
    active = np.asarray(active_positions)
    if len(active) <= n:
        return tuple(int(i) for i in active)
    idx = np.linspace(0, len(active) - 1, n).round().astype(int)
    return tuple(int(i) for i in active[idx])


def _style_axis(ax, xlabel, ylabel, title):
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.set_title(title)
    ax.grid(alpha=0.22)
    ax.legend(frameon=True)


def _save_figure(fig, path):
    fig.tight_layout()
    fig.savefig(path, dpi=220, bbox_inches="tight")
    plt.close(fig)


def _load(path):
    d = np.load(path)
    return {
        "steps": d["steps"],
        "mean_loss": d["mean_loss"],
        "logsnr": d["logsnr"],
        "valid_count": d["valid_count"],
    }


def compute_gradients(
    input_npz,
    output_npz,
    smooth_frac=0.005,
    plot_dir=None,
    active_positions=None,
    plot_positions=None,
    min_active_frac=0.5,
):
    """Stage 2: compute signed dE/dlambda for every active token position."""
    d = _load(input_npz)
    loss, logsnr, count = d["mean_loss"], d["logsnr"], d["valid_count"]
    T, L = loss.shape

    if active_positions is None:
        active_positions = infer_active_positions(count, min_frac=min_active_frac)
    if plot_positions is None:
        plot_positions = _default_plot_positions(active_positions)

    smooth_loss = np.full((T, L), np.nan, dtype=np.float64)
    gradient = np.full((T, L), np.nan, dtype=np.float64)

    for i in active_positions:
        valid = (
            np.isfinite(loss[:, i])
            & np.isfinite(logsnr[:, i])
            & (count[:, i] > 0)
        )
        idx = np.flatnonzero(valid)
        if idx.size < 4:
            continue

        order = np.argsort(logsnr[idx, i])
        idx_sorted = idx[order]
        x = logsnr[idx_sorted, i].astype(np.float64)
        y = loss[idx_sorted, i].astype(np.float64)

        # Same smoothing rule as the reference.
        s = smooth_frac * len(x) * max(float(np.var(y)), 1e-12)
        spline = UnivariateSpline(x, y, k=3, s=s)

        smooth_loss[idx_sorted, i] = spline(x)
        gradient[idx_sorted, i] = spline.derivative()(x)

    np.savez_compressed(
        output_npz,
        steps=d["steps"],
        logsnr=logsnr,
        valid_count=count,
        mean_loss=loss,
        smooth_loss=smooth_loss,
        gradient=gradient,
        active_positions=np.asarray(active_positions),
        smooth_frac=np.asarray(smooth_frac),
    )
    print(f"Stage 2 saved: {output_npz}")
    print(f"Active positions ({len(active_positions)}): {list(active_positions)}")

    if plot_dir is None:
        return

    out = Path(plot_dir)
    out.mkdir(parents=True, exist_ok=True)

    for i in plot_positions:
        valid = (
            np.isfinite(loss[:, i])
            & np.isfinite(smooth_loss[:, i])
            & np.isfinite(logsnr[:, i])
        )
        idx = np.flatnonzero(valid)
        idx = idx[np.argsort(logsnr[idx, i])]

        # Raw + smoothed E_i(lambda).
        fig, ax = plt.subplots(figsize=(9.5, 4.8))
        ax.plot(
            logsnr[idx, i],
            loss[idx, i],
            linewidth=1.0,
            alpha=0.65,
            label="Observed validation trajectory",
        )
        ax.plot(
            logsnr[idx, i],
            smooth_loss[idx, i],
            linewidth=2.0,
            label="Smoothed trajectory",
        )
        _style_axis(
            ax,
            "Log-SNR",
            "Validation embedding MSE",
            f"Stage 2 — token position {i}: trajectory smoothing",
        )
        _save_figure(fig, out / f"stage2_smoothing_position_{i}.png")

        # Signed derivative.
        fig, ax = plt.subplots(figsize=(9.5, 4.4))
        ax.plot(
            logsnr[idx, i],
            gradient[idx, i],
            linewidth=1.4,
            label=r"$dE_i/d\lambda$",
        )
        ax.axhline(0.0, linewidth=1.0, linestyle="--", label="Zero derivative")
        _style_axis(
            ax,
            "Log-SNR",
            r"$dE_i/d\lambda$",
            f"Stage 2 — token position {i}: trajectory gradient",
        )
        _save_figure(fig, out / f"stage2_gradient_position_{i}.png")

    print(f"Stage-2 plots saved for positions: {plot_positions}")


def monitor_density(gradient_npz, output_dir, mode="paper", plot_positions=None):
    """
    Stage 3: build token-wise density from Stage-2 gradients.

    mode="paper":
        a = max(-exp(lambda) * dE/dlambda, 0)
    mode="magnitude":
        a = exp(lambda) * |dE/dlambda|

    Density:
        p(lambda) proportional to sqrt(a(lambda))
    """
    d = np.load(gradient_npz)
    steps = d["steps"]
    logsnr = d["logsnr"]
    grad = d["gradient"]
    T, L = grad.shape

    # Read back the active-position set Stage 2 computed/received, rather
    # than recomputing it independently -- keeps the two stages from ever
    # silently disagreeing about which positions are active.
    active_positions = tuple(int(i) for i in d["active_positions"])
    if plot_positions is None:
        plot_positions = _default_plot_positions(active_positions)

    signed_activity = -np.exp(np.clip(logsnr, -50.0, 50.0)) * grad

    if mode == "paper":
        activity = np.maximum(signed_activity, 0.0)
    elif mode == "magnitude":
        activity = np.abs(signed_activity)
    else:
        raise ValueError("mode must be 'paper' or 'magnitude'")

    density = np.full((T, L), np.nan, dtype=np.float64)

    for i in active_positions:
        valid = np.isfinite(activity[:, i]) & np.isfinite(logsnr[:, i])
        idx = np.flatnonzero(valid)
        if idx.size < 2:
            continue

        order = np.argsort(logsnr[idx, i])
        idx_sorted = idx[order]
        x = logsnr[idx_sorted, i].astype(np.float64)
        w = np.sqrt(np.maximum(activity[idx_sorted, i], 0.0))

        area = np.trapezoid(w, x)
        if area > 0:
            density[idx_sorted, i] = w / area

    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    density_npz = out / f"density_profile_{mode}.npz"
    np.savez_compressed(
        density_npz,
        steps=steps,
        logsnr=logsnr,
        signed_activity=signed_activity,
        activity=activity,
        density=density,
        active_positions=np.asarray(active_positions),
    )
    print(f"Stage 3 saved: {density_npz}")

    # Individual density profiles for representative positions.
    for i in plot_positions:
        valid = np.isfinite(density[:, i])
        idx = np.flatnonzero(valid)
        idx = idx[np.argsort(steps[idx])]

        fig, ax = plt.subplots(figsize=(10, 4.6))
        ax.plot(
            steps[idx],
            density[idx, i],
            linewidth=1.15,
            label=fr"$p_{{{i}}}(\lambda_t)$",
        )
        ax.fill_between(
            steps[idx],
            0.0,
            density[idx, i],
            alpha=0.18,
        )
        ax.invert_xaxis()
        _style_axis(
            ax,
            "Reverse diffusion step",
            r"$p_i(\lambda_t)$",
            f"Stage 3 — token position {i}: reduced-step density",
        )
        _save_figure(fig, out / f"density_position_{i}.png")

    # Compact comparison of representative positions, normalized only for display.
    fig, ax = plt.subplots(figsize=(10.5, 5.0))
    for i in plot_positions:
        y = density[:, i].copy()
        valid = np.isfinite(y)
        if not np.any(valid):
            continue
        ymax = np.nanmax(y)
        if ymax > 0:
            y = y / ymax
        ax.plot(
            steps[valid],
            y[valid],
            linewidth=1.2,
            label=f"Position {i}",
        )
    ax.invert_xaxis()
    _style_axis(
        ax,
        "Reverse diffusion step",
        "Normalized density (visualization only)",
        "Stage 3 — representative token-wise density profiles",
    )
    _save_figure(fig, out / "density_selected_positions_normalized.png")

    # All active positions as a row-normalized heatmap for visual comparison.
    active = np.asarray(active_positions)
    heat = density[:, active].T.astype(np.float64)
    for r in range(heat.shape[0]):
        m = np.nanmax(heat[r])
        if np.isfinite(m) and m > 0:
            heat[r] /= m
    heat = np.nan_to_num(heat, nan=0.0)

    fig, ax = plt.subplots(figsize=(12, 7))
    im = ax.imshow(
        heat[:, ::-1],
        aspect="auto",
        origin="lower",
        extent=[steps[-1], steps[0], active[0] - 0.5, active[-1] + 0.5],
    )
    ax.set_xlabel("Reverse diffusion step")
    ax.set_ylabel("Token position")
    ax.set_title("Stage 3 — token-wise density heatmap (row-normalized)")
    cbar = fig.colorbar(im, ax=ax)
    cbar.set_label("Normalized density")
    _save_figure(fig, out / "density_heatmap_active_positions.png")

    print(f"Stage-3 plots saved for positions: {plot_positions}")
    print("Stage-3 all-active-position heatmap saved: density_heatmap_active_positions.png")


def allocate_schedule(
    density_npz,
    trajectory_npz,
    output_path,
    K=10,
    plot_dir=None,
    plot_positions=None,
):
    """
    Stage 4: practical finite-step allocation.

    1) Divide the T-step trajectory into approximately 2K timestep bins.
    2) For each active token position, compute the area of p_i(lambda_t)
       inside every bin on the timestep axis.
    3) Keep the K-2 highest-area bins.
    4) Choose one density-weighted representative timestep from each bin.
    5) Force the two trajectory endpoints and form J[K, L].

    Positions outside the active set (see `infer_active_positions`) are left
    on the uniform K-step baseline -- this is the direct analogue of the
    reference leaving non-caption positions on the uniform schedule, just
    with the active set determined from data instead of a fixed range.

    The continuous density is still learned in log-SNR space in Stage 3;
    this is only its practical discretization onto the finite trajectory.
    """
    dens = np.load(density_npz)
    traj = np.load(trajectory_npz)

    steps = traj["steps"].astype(np.int64)
    loss = traj["mean_loss"].astype(np.float64)
    logsnr = traj["logsnr"].astype(np.float64)
    density = dens["density"].astype(np.float64)

    if loss.shape != density.shape or logsnr.shape != density.shape:
        raise ValueError(
            f"Shape mismatch: loss={loss.shape}, logsnr={logsnr.shape}, "
            f"density={density.shape}"
        )

    T, L = density.shape
    if not (2 <= K <= T):
        raise ValueError(f"K must satisfy 2 <= K <= {T}, got K={K}")

    # Automatic practical bin width: about 2K candidate regions.
    bin_size = max(1, int(round(T / (2.0 * K))))

    active_positions = tuple(int(i) for i in dens["active_positions"])
    if plot_positions is None:
        plot_positions = _default_plot_positions(active_positions)

    high_noise_step = int(np.max(steps))
    clean_step = int(np.min(steps))

    uniform_steps = np.rint(
        np.linspace(high_noise_step, clean_step, K)
    ).astype(np.int64)

    # J stores the FINAL retained schedule for EVERY token position.
    # Positions outside the active set remain on the uniform baseline.
    J = np.repeat(uniform_steps[:, None], L, axis=1)
    selected_logsnr = np.full((K, L), np.nan, dtype=np.float64)

    bin_starts = np.arange(clean_step, high_noise_step + 1, bin_size)
    bin_ends = np.minimum(bin_starts + bin_size - 1, high_noise_step)
    n_bins = len(bin_starts)

    bin_areas = np.zeros((n_bins, L), dtype=np.float64)
    selected_bins = np.full((max(K - 2, 0), L), -1, dtype=np.int64)

    for i in active_positions:
        p = density[:, i]
        valid = (
            np.isfinite(p)
            & np.isfinite(logsnr[:, i])
            & np.isfinite(loss[:, i])
        )

        for b, (lo, hi) in enumerate(zip(bin_starts, bin_ends)):
            mask = valid & (steps >= lo) & (steps <= hi)
            mask &= (steps != clean_step) & (steps != high_noise_step)

            idx = np.flatnonzero(mask)
            if idx.size == 0:
                continue

            idx = idx[np.argsort(steps[idx])]
            x = steps[idx].astype(np.float64)
            y = np.maximum(p[idx], 0.0)

            area = float(y[0]) if idx.size == 1 else float(np.trapezoid(y, x))
            bin_areas[b, i] = max(area, 0.0)

        n_pick = K - 2
        if n_pick > 0:
            usable = np.flatnonzero(bin_areas[:, i] > 0)
            if usable.size < n_pick:
                print(
                    f"WARNING position {i}: only {usable.size} nonzero bins; "
                    "falling back to uniform schedule."
                )
                continue

            ranked = usable[np.argsort(bin_areas[usable, i])[::-1]]
            chosen_bins = ranked[:n_pick]
            selected_bins[:, i] = chosen_bins

            chosen_interior = []
            for b in chosen_bins:
                lo, hi = bin_starts[b], bin_ends[b]
                mask = (
                    valid
                    & (steps >= lo)
                    & (steps <= hi)
                    & (steps != clean_step)
                    & (steps != high_noise_step)
                )
                idx = np.flatnonzero(mask)

                w = np.maximum(p[idx], 0.0)
                if np.sum(w) > 0:
                    center = float(np.sum(steps[idx] * w) / np.sum(w))
                    chosen = idx[np.argmin(np.abs(steps[idx] - center))]
                else:
                    chosen = idx[len(idx) // 2]

                chosen_interior.append(int(steps[chosen]))

            chosen_steps = np.asarray(
                [high_noise_step] + chosen_interior + [clean_step],
                dtype=np.int64,
            )
        else:
            chosen_steps = np.asarray(
                [high_noise_step, clean_step],
                dtype=np.int64,
            )

        chosen_steps = np.unique(chosen_steps)[::-1]

        if chosen_steps.size != K:
            raise RuntimeError(
                f"Position {i}: expected K={K} unique steps, got "
                f"{chosen_steps.size}: {chosen_steps.tolist()}"
            )

        J[:, i] = chosen_steps
        selected_logsnr[:, i] = logsnr[chosen_steps, i]

    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Main machine-readable archive.
    np.savez_compressed(
        output_path,
        J=J,
        selected_logsnr=selected_logsnr,
        uniform_steps=uniform_steps,
        bin_size=np.asarray(bin_size),
        bin_starts=bin_starts,
        bin_ends=bin_ends,
        bin_areas=bin_areas,
        selected_bins=selected_bins,
        endpoint_steps=np.asarray([high_noise_step, clean_step]),
        K=np.asarray(K),
        active_positions=np.asarray(active_positions),
    )

    # Explicit standalone matrix used later by the decoder.
    j_npy = output_path.with_name(output_path.stem + "_J.npy")
    np.save(j_npy, J)

    # Human-readable schedules for ALL positions and active positions only.
    all_csv = output_path.with_name(output_path.stem + "_all_positions.csv")
    active_csv = output_path.with_name(output_path.stem + "_active_positions.csv")

    header = "position," + ",".join(f"call_{k}" for k in range(K))
    all_table = np.column_stack([np.arange(L), J.T])
    active = np.asarray(active_positions, dtype=np.int64)
    active_table = np.column_stack([active, J[:, active].T])

    np.savetxt(all_csv, all_table, fmt="%d", delimiter=",", header=header, comments="")
    np.savetxt(active_csv, active_table, fmt="%d", delimiter=",", header=header, comments="")

    print(f"Stage 4 saved: {output_path}")
    print(f"J shape: {J.shape}")
    print(f"Bin size: {bin_size} steps ({n_bins} bins)")
    print(f"Decoder matrix saved: {j_npy}")
    print(f"All-position schedules saved: {all_csv}")
    print(f"Active-position schedules saved: {active_csv}")

    print("\n### STAGE-4 RETAINED STEPS ###")
    print(f"Uniform K={K}: {uniform_steps.tolist()}")
    for i in plot_positions:
        print(f"Adaptive position {i}: {J[:, i].tolist()}")

    print("\n### SELECTED HIGH-AREA BINS ###")
    for i in plot_positions:
        entries = []
        for b in selected_bins[:, i]:
            if b >= 0:
                entries.append(f"[{bin_starts[b]}-{bin_ends[b]}]:{bin_areas[b, i]:.4g}")
        print(f"Position {i}: " + ", ".join(entries))

    if plot_dir is None:
        return

    out = Path(plot_dir)
    out.mkdir(parents=True, exist_ok=True)

    for i in plot_positions:
        valid_t = np.isfinite(loss[:, i])
        idx_t = np.flatnonzero(valid_t)
        idx_t = idx_t[np.argsort(steps[idx_t])]

        adaptive_i = J[:, i]
        uniform_i = uniform_steps[np.isfinite(loss[uniform_steps, i])]

        valid_d = np.isfinite(density[:, i])
        idx_d = np.flatnonzero(valid_d)
        idx_d = idx_d[np.argsort(steps[idx_d])]

        uniform_d = uniform_steps[np.isfinite(density[uniform_steps, i])]
        adaptive_d = adaptive_i[np.isfinite(density[adaptive_i, i])]

        fig, ax = plt.subplots(figsize=(10.5, 5.0))
        ax.plot(steps[idx_d], density[idx_d, i], linewidth=1.25, label=fr"$p_{{{i}}}(\lambda_t)$", zorder=1)
        ax.fill_between(steps[idx_d], 0.0, density[idx_d, i], alpha=0.14, zorder=0)
        ax.scatter(uniform_d, density[uniform_d, i], marker="x", s=90, linewidths=2.2,
                    color="black", label=f"Uniform K={K}", zorder=4)
        ax.scatter(adaptive_d, density[adaptive_d, i], marker="o", s=82, facecolors="none",
                    edgecolors="red", linewidths=2.2, label=f"Adaptive K={K}", zorder=5)
        for t_sel in uniform_d:
            ax.axvline(int(t_sel), color="black", linewidth=0.7, linestyle=":", alpha=0.18, zorder=2)
        for t_sel in adaptive_d:
            ax.axvline(int(t_sel), color="red", linewidth=0.8, linestyle="--", alpha=0.20, zorder=2)
        ax.invert_xaxis()
        _style_axis(ax, "Reverse diffusion step", r"$p_i(\lambda_t)$",
                     f"Stage 4 — position {i}: density with uniform vs adaptive levels")
        _save_figure(fig, out / f"density_uniform_vs_adaptive_position_{i}_K{K}.png")

        fig, ax = plt.subplots(figsize=(10, 5))
        ax.plot(steps[idx_t], loss[idx_t, i], linewidth=1.25, label="Full trajectory", zorder=1)
        ax.scatter(uniform_i, loss[uniform_i, i], marker="x", s=85, linewidths=2.2,
                    color="black", label=f"Uniform K={K}", zorder=4)
        ax.scatter(adaptive_i, loss[adaptive_i, i], marker="o", s=80, facecolors="none",
                    edgecolors="red", linewidths=2.2, label=f"Adaptive K={K}", zorder=5)
        ax.invert_xaxis()
        _style_axis(ax, "Reverse diffusion step", "Validation embedding MSE",
                     f"Stage 4 — position {i}: uniform vs adaptive allocation")
        _save_figure(fig, out / f"trajectory_timestep_uniform_vs_adaptive_position_{i}_K{K}.png")

        valid_l = np.isfinite(loss[:, i]) & np.isfinite(logsnr[:, i])
        idx_l = np.flatnonzero(valid_l)
        idx_l = idx_l[np.argsort(logsnr[idx_l, i])]

        fig, ax = plt.subplots(figsize=(10, 5))
        ax.plot(logsnr[idx_l, i], loss[idx_l, i], linewidth=1.25, label="Full trajectory", zorder=1)
        ax.scatter(logsnr[uniform_i, i], loss[uniform_i, i], marker="x", s=85, linewidths=2.2,
                    color="black", label=f"Uniform K={K}", zorder=4)
        ax.scatter(logsnr[adaptive_i, i], loss[adaptive_i, i], marker="o", s=80, facecolors="none",
                    edgecolors="red", linewidths=2.2, label=f"Adaptive K={K}", zorder=5)
        _style_axis(ax, "Log-SNR", "Validation embedding MSE",
                     f"Stage 4 — position {i}: retained levels in log-SNR space")
        _save_figure(fig, out / f"trajectory_logsnr_uniform_vs_adaptive_position_{i}_K{K}.png")

        centers = 0.5 * (bin_starts + bin_ends)
        fig, ax = plt.subplots(figsize=(10, 4.6))
        ax.bar(centers, bin_areas[:, i], width=max(bin_size * 0.85, 1), label="Regional density area", alpha=0.72)
        picked = selected_bins[:, i]
        picked = picked[picked >= 0]
        if picked.size:
            ax.scatter(centers[picked], bin_areas[picked, i], marker="*", s=120, color="red",
                        label="Selected region", zorder=4)
        ax.invert_xaxis()
        _style_axis(ax, "Reverse diffusion step", "Area under density in region",
                     f"Stage 4 — position {i}: regional allocation scores")
        _save_figure(fig, out / f"bin_area_position_{i}_K{K}.png")

    active = np.asarray(active_positions, dtype=np.int64)
    allocation_heat = J[:, active].T

    fig, ax = plt.subplots(figsize=(10, 7))
    im = ax.imshow(allocation_heat, aspect="auto", origin="lower")
    ax.set_xlabel("Reduced decoding call")
    ax.set_ylabel("Token position")
    ax.set_title(f"Stage 4 — adaptive retained-step matrix, K={K}")
    ax.set_xticks(np.arange(K))
    ax.set_xticklabels([str(k + 1) for k in range(K)])
    yticks = np.arange(0, len(active), max(1, len(active) // 20))
    ax.set_yticks(yticks)
    ax.set_yticklabels(active[yticks])
    cbar = fig.colorbar(im, ax=ax)
    cbar.set_label("Original diffusion timestep")
    _save_figure(fig, out / f"allocation_heatmap_active_positions_K{K}.png")

    print(f"Stage-4 visualizations saved in: {out}")


def main():
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="stage", required=True)

    p2 = sub.add_parser("gradient")
    p2.add_argument("--input", required=True, help="Stage-1 profile .npz (reduced_step_profile.py output)")
    p2.add_argument("--output", required=True)
    p2.add_argument("--smooth-frac", type=float, default=0.005)
    p2.add_argument("--plot-dir", default=None)
    p2.add_argument("--min-active-frac", type=float, default=0.5,
                     help="A position must have non-pad coverage at this fraction "
                          "of profiled timesteps to be treated as active.")

    p3 = sub.add_parser("monitor")
    p3.add_argument("--input", required=True, help="Stage-2 gradient .npz")
    p3.add_argument("--output-dir", required=True)
    p3.add_argument("--mode", choices=("paper", "magnitude"), default="paper")

    p4 = sub.add_parser("allocate")
    p4.add_argument("--input", required=True, help="Stage-3 density .npz")
    p4.add_argument("--trajectory", required=True, help="Stage-1 trajectory .npz for loss-vs-logSNR overlays")
    p4.add_argument("--output", required=True)
    p4.add_argument("--K", type=int, required=True)
    p4.add_argument("--plot-dir", default=None)

    args = parser.parse_args()

    if args.stage == "gradient":
        compute_gradients(
            args.input,
            args.output,
            args.smooth_frac,
            args.plot_dir,
            min_active_frac=args.min_active_frac,
        )
    elif args.stage == "monitor":
        monitor_density(args.input, args.output_dir, args.mode)
    else:
        allocate_schedule(
            density_npz=args.input,
            trajectory_npz=args.trajectory,
            output_path=args.output,
            K=args.K,
            plot_dir=args.plot_dir,
        )


if __name__ == "__main__":
    main()